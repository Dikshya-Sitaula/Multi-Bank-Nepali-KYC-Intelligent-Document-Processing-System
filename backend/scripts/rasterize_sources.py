"""Rasterize source PDFs to template page images and run the image-quality triage.

WHY:
- The pipeline works on images, so each blank bank form is rendered to 300 DPI PNGs that
  become the template reference pages (templates/<id>/pages/page_N.png).
- PDF text layers are NOT used: some forms use legacy Nepali fonts (e.g. Preeti) whose
  text extracts as garbage.
- Quality triage (resolution, sharpness, contrast) decides which forms are clean enough to
  generate training data from and which are kept for evaluation only (SPEC section 5).

Source PDFs in data/source_forms/ are opened read-only and never modified.
The template-id to filename mapping is configuration: config/source_forms.yaml.

Run:  .venv\\Scripts\\python.exe backend\\scripts\\rasterize_sources.py
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from datetime import datetime
from pathlib import Path

import cv2
import fitz  # PyMuPDF
import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "backend"))

from app.services.quality.metrics import page_quality_metrics  # noqa: E402

CONFIG = ROOT / "config" / "source_forms.yaml"
SOURCE_DIR = ROOT / "data" / "source_forms"
TEMPLATES_DIR = ROOT / "templates"
REPORT = ROOT / "reports" / "source_quality.md"


def sha256(path: Path) -> str:
    """Hash of the source PDF, so we can prove later that it was never modified."""
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def rasterize(pdf_path: Path, out_dir: Path, dpi: int) -> list[dict]:
    """Render every page to PNG and measure its quality."""
    out_dir.mkdir(parents=True, exist_ok=True)
    pages = []
    with fitz.open(pdf_path) as doc:
        for i, page in enumerate(doc, start=1):
            pix = page.get_pixmap(dpi=dpi, alpha=False)
            img = np.frombuffer(pix.samples, dtype=np.uint8).reshape(pix.h, pix.w, pix.n)
            if pix.n == 3:
                bgr = cv2.cvtColor(img, cv2.COLOR_RGB2BGR)
            else:
                bgr = cv2.cvtColor(img, cv2.COLOR_GRAY2BGR)
            out = out_dir / f"page_{i}.png"
            cv2.imwrite(str(out), bgr)
            info = {
                "page": i,
                "file": out.relative_to(ROOT).as_posix(),
                "page_size_pt": [round(page.rect.width, 1), round(page.rect.height, 1)],
                "has_text_layer": bool(page.get_text("text").strip()),
                "vector_drawings": len(page.get_drawings()),
                "embedded_images": len(page.get_images(full=True)),
            }
            info.update(page_quality_metrics(bgr))
            pages.append(info)
    return pages


def write_report(results: dict, missing: list[str], thresholds: dict, dpi: int) -> None:
    lines = [
        "# Source form quality triage", "",
        "Generated by `backend/scripts/rasterize_sources.py` on "
        f"{datetime.now().isoformat(timespec='seconds')}.",
        f"Rasterized with PyMuPDF at {dpi} DPI. PDF text layers are not used.", "",
        "## Thresholds (from `config/source_forms.yaml`)", "",
        f"- Minimum sharpness (variance of Laplacian): {thresholds['min_sharpness']}",
        f"- Minimum RMS contrast: {thresholds['min_contrast']}", "",
        "A form is **clean** (training template) only if every page passes both thresholds.", "",
    ]
    if missing:
        lines += ["## Missing or unreadable source files", ""]
        lines += [f"- {m}" for m in missing]
        lines.append("")
    if not results:
        lines += ["## Results", "", "No source PDF could be rasterized. Nothing was measured yet.", ""]
    for tid, info in results.items():
        lines += [
            f"## `{tid}` ({info['source_file']})", "",
            f"Verdict: **{info['quality_verdict']}**. Suggested role: {info['suggested_role']}.", "",
            "| Page | Size px | Sharpness | Contrast | Mean | Text layer | Vector drawings | Embedded images |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for p in info["pages"]:
            lines.append(
                f"| {p['page']} | {p['width_px']}x{p['height_px']} | "
                f"{p['sharpness_laplacian_var']:.1f} | {p['contrast_rms']:.1f} | "
                f"{p['mean_intensity']:.1f} | {p['has_text_layer']} | "
                f"{p['vector_drawings']} | {p['embedded_images']} |"
            )
        lines.append("")
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description="Rasterize source PDFs and triage quality.")
    ap.add_argument("--dpi", type=int, default=300)
    args = ap.parse_args()

    cfg = yaml.safe_load(CONFIG.read_text(encoding="utf-8"))
    thresholds = cfg["quality_thresholds"]
    results: dict[str, dict] = {}
    missing: list[str] = []

    for tid, entry in cfg["forms"].items():
        pdf = SOURCE_DIR / entry["file"]
        if not pdf.exists():
            suffix = " (optional)" if entry.get("optional") else ""
            missing.append(f"`{tid}`: `data/source_forms/{entry['file']}` not found{suffix}")
            continue
        try:
            pages = rasterize(pdf, TEMPLATES_DIR / tid / "pages", args.dpi)
        except Exception as exc:  # noqa: BLE001 - unreadable PDF is reported, not fatal
            missing.append(f"`{tid}`: `{entry['file']}` unreadable ({type(exc).__name__}: {exc})")
            continue
        min_sharp = min(p["sharpness_laplacian_var"] for p in pages)
        min_contrast = min(p["contrast_rms"] for p in pages)
        clean = min_sharp >= thresholds["min_sharpness"] and min_contrast >= thresholds["min_contrast"]
        info = {
            "template_id": tid,
            "bank_name": entry.get("bank_name"),
            "source_file": pdf.relative_to(ROOT).as_posix(),
            "source_sha256": sha256(pdf),
            "rasterized_at": datetime.now().isoformat(timespec="seconds"),
            "dpi": args.dpi,
            "page_count": len(pages),
            "quality_verdict": "clean" if clean else "low_quality",
            "suggested_role": "training" if clean else "evaluation_only (held-out unseen template)",
            "pages": pages,
        }
        (TEMPLATES_DIR / tid / "source_info.json").write_text(json.dumps(info, indent=2), encoding="utf-8")
        results[tid] = info
        print(f"{tid}: {len(pages)} pages, verdict={info['quality_verdict']}")

    write_report(results, missing, thresholds, args.dpi)
    for m in missing:
        print("MISSING:", m)
    print(f"Written {REPORT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
